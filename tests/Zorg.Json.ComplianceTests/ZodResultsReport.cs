using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Zorg.Json.ComplianceTests;

/// <summary>Writes tools/zod-compare/RESULTS.md from the same analysis the tests assert on.</summary>
internal static class ZodResultsReport
{
    public static string Build(ZodAnalysis analysis)
    {
        StringBuilder text = new();
        int cases = ZodFixture.Cases.Length;
        int documents = ZodFixture.Documents.Length;
        Classified[] items = [.. analysis.Items];

        text.AppendLine("# Zod comparison results");
        text.AppendLine();
        text.AppendLine($"Generated by `ZORG_ZOD_WRITE=results dotnet test` against Zod {ZodFixture.Version}. Do not edit by hand.");
        text.AppendLine();
        text.AppendLine($"- Catalogue: {cases} schema pairs, {documents} shared documents.");
        text.AppendLine($"- Behaviour comparisons: {analysis.Compared["behaviour"]}.");
        text.AppendLine($"- Disagreements: {items.Count(i => i.Difference.Part == "behaviour")} behaviour, {items.Count(i => i.Difference.Part == "interop-in")} importing Zod JSON Schema, {items.Count(i => i.Difference.Part == "interop-out")} Zod reading Zorg JSON Schema, {items.Count(i => i.Difference.Part == "openapi-refusal")} OpenAPI 3.0 refusals.");
        text.AppendLine($"- Unlisted disagreements (the tests fail on any): {items.Count(i => !i.IsExplained)}.");
        text.AppendLine();

        text.AppendLine("## Behaviour, by status");
        text.AppendLine();
        text.AppendLine("| Status | Meaning | Disagreements |");
        text.AppendLine("|---|---|---:|");
        text.AppendLine($"| design | Documented in docs/ | {items.Count(i => i.Difference.Part == "behaviour" && i.Rule?.Status == "design")} |");
        text.AppendLine($"| undocumented-design | Intended, but the docs do not say so | {items.Count(i => i.Difference.Part == "behaviour" && i.Rule?.Status == "undocumented-design")} |");
        text.AppendLine($"| zod-behaviour | Zod's own quirk | {items.Count(i => i.Difference.Part == "behaviour" && i.Rule?.Status == "zod-behaviour")} |");
        text.AppendLine($"| suspected_bug | Zorg looks wrong | {items.Count(i => i.Difference.Part == "behaviour" && i.Rule?.Status == "suspected_bug")} |");
        text.AppendLine();
        text.AppendLine("## Behaviour, by category");
        text.AppendLine();
        text.AppendLine("| Category | Status | Disagreements | Rules |");
        text.AppendLine("|---|---|---:|---:|");

        foreach (var group in items.Where(i => i.Difference.Part == "behaviour" && i.Rule is not null).GroupBy(i => (i.Rule!.Category, i.Rule.Status)).OrderByDescending(g => g.Count()))
        {
            text.AppendLine($"| {group.Key.Category} | {group.Key.Status} | {group.Count()} | {group.Select(i => i.Rule!.Id).Distinct().Count()} |");
        }

        text.AppendLine();
        text.AppendLine("## Suspected bugs");
        text.AppendLine();

        foreach (KnownDifference bug in ZodFixture.KnownDifferences.Where(k => k.Status == "suspected_bug"))
        {
            text.AppendLine($"- **{bug.Id}** ({items.Count(i => i.Rule?.Id == bug.Id)} disagreements): {bug.Reason} Repro: {bug.Repro}");
        }

        text.AppendLine();
        text.AppendLine("## Interop: importing what Zod writes (`Z.FromJsonSchema`)");
        text.AppendLine();
        text.AppendLine("| Target / io / reused | Comparisons | Same as native difference | Listed | Refused by import |");
        text.AppendLine("|---|---:|---:|---:|---:|");

        foreach (string target in ZodAnalysis.ImportTargets)
        {
            foreach (string io in new[] { "input", "output" })
            {
                foreach (string reused in new[] { "inline", "ref" })
                {
                    Classified[] part = [.. items.Where(i => i.Difference.Part == "interop-in" && i.Difference.Target == target && i.Difference.Io == io && i.Difference.Reused == reused)];
                    int compared = analysis.Compared.GetValueOrDefault($"import {target} {io} {reused}");
                    text.AppendLine($"| {target} / {io} / {reused} | {compared} | {part.Count(i => i.Inherited)} | {part.Count(i => i.Rule is not null && i.Difference.Kind != "refused")} | {part.Count(i => i.Difference.Kind == "refused")} |");
                }
            }
        }

        text.AppendLine();
        text.AppendLine("A `ref` row runs only for schemas where Zod's `reused: \"ref\"` output differs from `inline`, so it has fewer comparisons. For `io: output`, only the documents Zod accepted are run, using Zod's output, and Zorg has to accept them. \"Same as native difference\" counts a disagreement that Zorg's own schema has too, which the behaviour section already lists.");
        text.AppendLine();
        text.AppendLine($"Zod wrote a JSON Schema for every catalogue schema in every target, so none were skipped as unrepresentable ({analysis.Refused.Values.Sum()} refusals).");
        text.AppendLine();
        text.AppendLine("## Interop: OpenAPI 3.0 documents");
        text.AppendLine();
        text.AppendLine($"{analysis.Compared.GetValueOrDefault("openapi-3.0 refusal")} documents say `nullable`, and {items.Count(i => i.Difference.Part == "openapi-refusal")} of them were not refused with `unsupported_dialect` when no dialect was chosen.");
        text.AppendLine();
        text.AppendLine($"Read with `DefaultDialect = OpenApi30`: {analysis.Compared.GetValueOrDefault("openapi-3.0 read")} comparisons with Zod's verdicts, {items.Count(i => i.Difference.Part == "openapi-read" && i.Inherited)} the same as a native difference, {items.Count(i => i.Difference.Part == "openapi-read" && i.Rule is not null)} listed, {items.Count(i => i.Difference.Part == "openapi-read" && i.Difference.Kind == "refused")} refused.");
        text.AppendLine();
        text.AppendLine("## Interop: Zod reading what Zorg writes (`z.fromJSONSchema`)");
        text.AppendLine();
        text.AppendLine("| Target | Comparisons | Same as native difference | Listed | Refused by Zod |");
        text.AppendLine("|---|---:|---:|---:|---:|");

        foreach (string target in ZodAnalysis.EmitTargets)
        {
            Classified[] part = [.. items.Where(i => i.Difference.Part == "interop-out" && i.Difference.Target == target)];
            text.AppendLine($"| {target} | {analysis.Compared.GetValueOrDefault($"zod-reads {target}")} | {part.Count(i => i.Inherited)} | {part.Count(i => i.Rule is not null && i.Difference.Kind != "refused")} | {part.Count(i => i.Difference.Kind == "refused")} |");
        }

        text.AppendLine();
        text.AppendLine("## Every entry in known-differences.json");
        text.AppendLine();
        text.AppendLine("| Id | Part | Category | Status | Disagreements |");
        text.AppendLine("|---|---|---|---|---:|");

        foreach (KnownDifference known in ZodFixture.KnownDifferences)
        {
            text.AppendLine($"| {known.Id} | {known.Part.Replace("|", " + ", System.StringComparison.Ordinal)} | {known.Category} | {known.Status} | {items.Count(i => i.Rule?.Id == known.Id)} |");
        }

        text.AppendLine();
        text.AppendLine("## Not compared");
        text.AppendLine();
        text.AppendLine("- Zod features with no Zorg counterpart: `transform`, `pipe`, `preprocess`, codecs, `brand`, `z.date`, `z.bigint`, `z.map`, `z.set`, `z.undefined`, `z.custom`, async refinements, and `.catch()`.");
        text.AppendLine("- Documents JSON cannot hold: `undefined`, `NaN`, `-Infinity` and `Infinity` (the text `1e400` is the nearest thing). An absent top-level value is not representable either.");
        text.AppendLine("- Zorg's output direction (`Direction = Output`): `z.fromJSONSchema` is an input reader, so only the input document is read by Zod.");
        text.AppendLine("- Draft-04 and OpenAPI 3.0 as a target of Zorg's emitter: Zod's reader takes Draft 2020-12 and Draft-07. Zorg emits no Draft-04.");
        text.AppendLine("- Targets other than the four requested: Zod 4.6.7 also takes `openapi-3.1`, `draft-2019-09` and `draft-06`, and writes a document without `$schema` for each. Zorg's `OpenApi30` and `OpenApi31` emitter profiles are not compared with Zod either.");
        text.AppendLine("- Messages. Only issue codes and paths are compared, not text.");
        text.AppendLine("- Refinement exceptions: the catalogue's refinements do not throw.");
        return text.ToString();
    }
}
