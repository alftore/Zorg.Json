using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Zorg.Json.SourceGeneration;

/// <summary>
/// Writes a static <c>Schema</c> property for each type with <c>[GenerateSchema]</c>. What it writes is the fluent code a person would
/// write, so a generated schema is the same model as any other, and it uses the <c>JsonSerializerContext</c>, so it needs no reflection.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class SchemaGenerator : IIncrementalGenerator
{
    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValueProvider<ImmutableArray<TypeModel>> types = context.SyntaxProvider
            .ForAttributeWithMetadataName(TypeReader.AttributeName, static (_, _) => true, TypeReader.Read)
            .Collect();

        context.RegisterSourceOutput(types, static (output, models) =>
        {
            // A type with the attribute on two of its parts is one type. The compiler reports the repeated attribute.
            Dictionary<string, TypeModel> byName = [];
            HashSet<string> hints = new(StringComparer.OrdinalIgnoreCase);
            HashSet<Finding> reported = [];

            foreach (TypeModel model in models)
            {
                byName[model.FullName] = model;
            }

            foreach (TypeModel model in byName.Values)
            {
                foreach (Finding finding in model.Findings)
                {
                    if (reported.Add(finding))
                    {
                        output.ReportDiagnostic(finding.ToDiagnostic());
                    }
                }

                if (model.CanGenerate)
                {
                    string hint = model.Hint;

                    for (int number = 2; !hints.Add(hint); number++)
                    {
                        hint = model.Hint + "_" + number.ToString(System.Globalization.CultureInfo.InvariantCulture);
                    }

                    output.AddSource(hint + ".Schema.g.cs", SourceText.From(Write(model, byName), Encoding.UTF8));
                }
            }
        });
    }

    /// <summary>True when following generated schemas from <paramref name="from"/> leads to <paramref name="to"/>.</summary>
    private static bool Reaches(string from, string to, Dictionary<string, TypeModel> all)
    {
        HashSet<string> seen = new(StringComparer.Ordinal);
        Stack<string> pending = new();
        pending.Push(from);

        while (pending.Count > 0)
        {
            string name = pending.Pop();

            if (name == to)
            {
                return true;
            }

            if (seen.Add(name) && all.TryGetValue(name, out TypeModel? model))
            {
                foreach (PropertyModel property in model.Properties)
                {
                    if (property.Nested is { } nested)
                    {
                        pending.Push(nested);
                    }
                }
            }
        }

        return false;
    }

    private static string Reference(TypeModel owner, string nested, Dictionary<string, TypeModel> all)
    {
        // A cycle can't be built eagerly, so it goes through a named definition that is read when it's used.
        if (Reaches(nested, owner.FullName, all))
        {
            string name = SymbolText(nested.Replace("global::", string.Empty));
            return $"global::Zorg.Json.Schema.Lazy<{nested}>({name}, static () => {nested}.Schema)";
        }

        return $"{nested}.Schema";
    }

    private static string SymbolText(string text) => Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(text, quote: true);

    private static string Write(TypeModel model, Dictionary<string, TypeModel> all)
    {
        StringBuilder text = new();
        text.Append("// <auto-generated/>\n#nullable enable\n\n");

        if (model.Namespace is { } space)
        {
            text.Append("namespace ").Append(space).Append(";\n\n");
        }

        string schema = $"global::Zorg.Json.ObjectSchema<{model.FullName}>";
        string info = $"global::System.Text.Json.Serialization.Metadata.JsonTypeInfo<{model.FullName}>";
        string modifiers = model.HidesSchema ? "public static new" : "public static";

        text.Append(model.Declaration).Append(' ').Append(model.Name).Append("\n{\n");
        text.Append("    private static ").Append(schema).Append("? __zorgSchema;\n\n");
        text.Append("    /// <summary>The schema of this type, from its System.Text.Json contract and its validation attributes.</summary>\n");
        text.Append("    ").Append(modifiers).Append(' ').Append(schema).Append(" Schema =>\n");
        text.Append("        global::System.Threading.LazyInitializer.EnsureInitialized(ref __zorgSchema, __ZorgCreateSchema);\n\n");
        text.Append("    private static ").Append(schema).Append(" __ZorgCreateSchema() =>\n");
        text.Append("        global::Zorg.Json.Schema.Object((").Append(info).Append(')').Append(model.Context).Append(".Default.GetTypeInfo(typeof(").Append(model.FullName).Append("))!)");

        foreach (PropertyModel property in model.Properties)
        {
            text.Append("\n            .Property(static value => value.").Append(property.Name).Append(", ").Append(Argument(model, property, all)).Append(')');
        }

        if (model.TypeCalls.Length > 0)
        {
            text.Append("\n            ").Append(model.TypeCalls);
        }

        return text.Append(";\n}\n").ToString();
    }

    private static string Argument(TypeModel owner, PropertyModel property, Dictionary<string, TypeModel> all)
    {
        if (property.Nested is not { } nested)
        {
            return $"static schema => schema{property.Calls}";
        }

        string reference = Reference(owner, nested, all);
        return property.NestedIsItem ? $"static schema => schema.Items({reference}){property.Calls}" : reference + property.Calls;
    }
}
